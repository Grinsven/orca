// Jose fork-local: regenerates the explorer's Seti icon map and stylesheet from VS Code's
// theme-seti extension (MIT). Inputs are downloaded files, read as data only.
//
// Usage: node config/scripts/generate-seti-icon-theme.mjs <vs-seti-icon-theme.json> <dir of
//   VS Code built-in extension package.json files, named <extension>.package.json>
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const OUTPUT_DIR = 'src/renderer/src/fork/vscode-explorer'

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'))
}

function stripIdPrefix(id) {
  return id.replace(/^_/, '')
}

function lowerKeys(record, mapValue) {
  const result = {}
  for (const [key, value] of Object.entries(record)) {
    const lower = key.toLowerCase()
    // Why: the theme lists some names in two casings; the first entry wins, as in VS Code.
    if (!(lower in result)) {
      result[lower] = mapValue(value)
    }
  }
  return result
}

function collectLanguageAssociations(packagesDir, themedLanguageIds) {
  const fileNames = {}
  const fileExtensions = {}
  const manifests = fs
    .readdirSync(packagesDir)
    .filter((name) => name.endsWith('.package.json'))
    .sort()
  for (const manifest of manifests) {
    const languages = readJson(path.join(packagesDir, manifest)).contributes?.languages ?? []
    for (const language of languages) {
      const iconId = themedLanguageIds[language.id]
      if (!iconId) {
        continue
      }
      for (const fileName of language.filenames ?? []) {
        fileNames[fileName.toLowerCase()] ??= iconId
      }
      for (const extension of language.extensions ?? []) {
        fileExtensions[extension.replace(/^\./, '').toLowerCase()] ??= iconId
      }
    }
  }
  return { fileNames, fileExtensions }
}

function sortRecord(record) {
  return Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))
}

function main() {
  const [themePath, packagesDir] = process.argv.slice(2)
  if (!themePath || !packagesDir) {
    throw new Error('usage: generate-seti-icon-theme.mjs <theme.json> <packages dir>')
  }
  const theme = readJson(themePath)
  const languages = collectLanguageAssociations(packagesDir, theme.languageIds)
  const map = {
    defaultIcon: stripIdPrefix(theme.file),
    fileNames: sortRecord(lowerKeys(theme.fileNames, stripIdPrefix)),
    fileExtensions: sortRecord(lowerKeys(theme.fileExtensions, stripIdPrefix)),
    languageFileNames: sortRecord(lowerKeys(languages.fileNames, stripIdPrefix)),
    languageFileExtensions: sortRecord(lowerKeys(languages.fileExtensions, stripIdPrefix))
  }

  const usedIds = new Set([
    map.defaultIcon,
    ...Object.values(map.fileNames),
    ...Object.values(map.fileExtensions),
    ...Object.values(map.languageFileNames),
    ...Object.values(map.languageFileExtensions)
  ])
  const darkRules = []
  const lightRules = []
  for (const id of [...usedIds].sort()) {
    const dark = theme.iconDefinitions[`_${id}`]
    const light = theme.iconDefinitions[`_${id}_light`] ?? dark
    const selector = `[data-seti-icon='${id}']::before`
    // Why optional: a few glyphs have no color and inherit the row's text color, as in VS Code.
    const lightColor = light.fontColor ? `\n  color: ${light.fontColor};` : ''
    lightRules.push(`${selector} {\n  content: '${dark.fontCharacter}';${lightColor}\n}`)
    if (dark.fontColor) {
      darkRules.push(`.dark ${selector} {\n  color: ${dark.fontColor};\n}`)
    }
  }

  const header =
    '/* Generated by config/scripts/generate-seti-icon-theme.mjs from VS Code theme-seti (MIT, see LICENSE-seti.txt). Do not edit by hand. */'
  fs.writeFileSync(path.join(OUTPUT_DIR, 'seti-icon-map.json'), `${JSON.stringify(map, null, 2)}\n`)
  fs.writeFileSync(
    path.join(OUTPUT_DIR, 'seti-icon-glyphs.css'),
    `${header}\n${[...lightRules, ...darkRules].join('\n')}\n`
  )
}

main()
